-- Add only the catalog lookup tables missing from the sandbox schema subset.
-- This file can also upgrade an existing seeded sandbox without resetting it.
-- No production data, grants, functions, or secrets are copied.
BEGIN;

DO $$
BEGIN
    IF current_database() NOT IN (
        'life365_sandbox', 'life365_public_api_test_customer_sync'
    ) THEN
        RAISE EXCEPTION 'Product export support must target a local sandbox or test database';
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public.brands (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_name character varying(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.product_images (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL REFERENCES public.products(id),
    image_url character varying(512) NOT NULL
);

COMMIT;
